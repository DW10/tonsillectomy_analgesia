# Writes submission/xref-map.yml: fixed text for every `@sec-sm-*` reference, used by
# xref-hardcode.lua in the submission documents (outside the book Quarto cannot number
# appendix sections itself).
#
# The numbers are computed from the headings of supplementary_materials.qmd, laid out as in
# supplement.docx: the "# Supplementary materials" title is unnumbered, `##` headings are
# sections 1, 2, ... and `###` headings are 1.1, 1.2, ... Run by pre_render.R before every
# render, so the map follows the headings automatically.

write_xref_map <- function(src = "supplementary_materials.qmd",
                           out = "submission/xref-map.yml",
                           prefix = "Supplementary Material") {
  lines <- readLines(src, warn = FALSE)
  in_code <- FALSE
  counters <- integer(0)
  map <- character(0)
  for (ln in lines) {
    if (grepl("^\\s*```", ln)) { in_code <- !in_code; next }
    if (in_code) next
    if (!grepl("^#{1,6} ", ln)) next
    level <- attr(regexpr("^#+", ln), "match.length")
    attrs <- if (grepl("\\{[^}]*\\}\\s*$", ln)) sub(".*(\\{[^}]*\\})\\s*$", "\\1", ln) else ""
    has_id <- grepl("#sec-", attrs)
    id <- if (has_id) sub(".*#(sec-[A-Za-z0-9_-]+).*", "\\1", attrs) else NA
    unnumbered <- grepl("unnumbered", attrs)
    if (level == 1) {
      if (has_id) map[id] <- prefix
      next
    }
    if (unnumbered) next
    depth <- level - 1
    counters <- c(counters, integer(max(0, depth - length(counters))))[seq_len(max(depth, length(counters)))]
    counters[depth] <- counters[depth] + 1L
    counters <- counters[seq_len(depth)]
    if (has_id) map[id] <- paste(prefix, "Section", paste(counters, collapse = "."))
  }
  # The separate supplementary tables and figures chapter has no numbered sections
  map["sec-sm-tables-figures"] <- "Supplementary Tables and Figures"
  yaml <- c(
    "# GENERATED by scripts/xref_map.R from the headings of supplementary_materials.qmd.",
    "# Do not edit: pre_render.R rewrites it before every render.",
    "xref-hardcode:",
    sprintf("  %s: \"%s\"", names(map), map)
  )
  writeLines(yaml, out)
  invisible(map)
}
